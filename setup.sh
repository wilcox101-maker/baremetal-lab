#!/usr/bin/env bash
# baremetal-lab — interactive setup

set -e

CONFIG_DIR="${CONFIG_DIR:-$HOME/baremetal-lab}"
mkdir -p "$CONFIG_DIR"
cd "$CONFIG_DIR"

echo "=========================================="
echo "  Baremetal Lab — Interactive Setup"
echo "=========================================="
echo

echo "--- Hardware ---"

echo "CPU cores available to containers (1-8):"
select CPU in 1 2 4 6 8; do
  [ -n "$CPU" ] && break
done

echo
echo "RAM to allocate to Docker host (GB):"
select RAM in 2 4 8 12 16; do
  [ -n "$RAM" ] && break
done

echo
echo "Primary storage type:"
select STORAGE in "NVMe/SSD (local)" "USB drive" "Network share"; do
  [ -n "$STORAGE" ] && break
done

echo
echo "Number of Ethernet NICs:"
select NICS in "1 (WAN only — use USB NIC for LAN)" "2 (WAN + LAN)" "3+"; do
  [ -n "$NICS" ] && break
done

echo
echo "Wireless:"
select WIFI in "None (use separate AP)" "USB Wi-Fi adapter" "Built-in"; do
  [ -n "$WIFI" ] && break
done

echo
echo "USB devices to pass through (select all that apply, 0 to finish):"
USB_LIST=()
options=("USB storage" "Zigbee/Z-Wave dongle" "Bluetooth adapter" "USB Wi-Fi" "Coral TPU (Frigate)" "None")
while true; do
  select opt in "${options[@]}" "Done"; do
    case $opt in
      Done) break 2 ;;
      None) USB_LIST=(); break 2 ;;
      *) USB_LIST+=("$opt"); break ;;
    esac
  done
done

echo
echo "--- Services ---"
echo "Select services to enable (space-separated numbers, or 'all'):"

SERVICES=(
  "AdGuard Home"
  "Unbound"
  "Home Assistant"
  "ESPHome"
  "Mosquitto (MQTT)"
  "Nextcloud"
  "Immich (photo backup)"
  "FileBrowser (simple file share)"
  "Frigate (NVR)"
  "Grafana"
  "Prometheus"
  "Uptime Kuma"
  "Nginx Proxy Manager"
  "Tailscale"
  "WireGuard (via OPNsense)"
)
for i in "${!SERVICES[@]}"; do
  echo "  $((i+1))) ${SERVICES[$i]}"
done
echo "  a) All"
read -r -p "Choice: " CHOICE

ENABLED=()
if [[ "$CHOICE" == "a" || "$CHOICE" == "all" ]]; then
  ENABLED=("${SERVICES[@]}")
else
  for n in $CHOICE; do
    ENABLED+=("${SERVICES[$((n-1))]}")
  done
fi

echo
echo "--- Network ---"
read -r -p "LAN subnet (default 192.168.50.0/24): " LAN_SUBNET
LAN_SUBNET=${LAN_SUBNET:-192.168.50.0/24}
read -r -p "Docker host IP (default 192.168.50.10): " HOST_IP
HOST_IP=${HOST_IP:-192.168.50.10}
read -r -p "Timezone (default America/Detroit): " TZ
TZ=${TZ:-America/Detroit}

echo
echo "Generating docker-compose.yml ..."

COMPOSE="$CONFIG_DIR/docker-compose.yml"
cat > "$COMPOSE" <<EOF
# Generated by baremetal-lab
# CPU cores: $CPU | RAM: ${RAM}G | Storage: $STORAGE
# NICs: $NICS | Wi-Fi: $WIFI
# LAN: $LAN_SUBNET | Host: $HOST_IP

version: "3.8"

networks:
  proxy:
  backend:

volumes:
EOF

for svc in "${ENABLED[@]}"; do
  case "$svc" in
    "AdGuard Home") echo "  adguard_work:" >> "$COMPOSE"; echo "  adguard_conf:" >> "$COMPOSE" ;;
    "Unbound") echo "  unbound_conf:" >> "$COMPOSE" ;;
    "Home Assistant") echo "  ha_config:" >> "$COMPOSE" ;;
    "ESPHome") echo "  esphome_config:" >> "$COMPOSE" ;;
    "Mosquitto (MQTT)") echo "  mosquitto_data:" >> "$COMPOSE"; echo "  mosquitto_log:" >> "$COMPOSE" ;;
    "Nextcloud") echo "  nextcloud_data:" >> "$COMPOSE"; echo "  nextcloud_db:" >> "$COMPOSE" ;;
    "Immich (photo backup)") echo "  immich_data:" >> "$COMPOSE"; echo "  immich_db:" >> "$COMPOSE" ;;
    "FileBrowser (simple file share)") echo "  filebrowser_data:" >> "$COMPOSE"; echo "  filebrowser_config:" >> "$COMPOSE" ;;
    "Frigate (NVR)") echo "  frigate_config:" >> "$COMPOSE"; echo "  frigate_media:" >> "$COMPOSE" ;;
    "Grafana") echo "  grafana_data:" >> "$COMPOSE" ;;
    "Prometheus") echo "  prometheus_data:" >> "$COMPOSE" ;;
    "Uptime Kuma") echo "  kuma_data:" >> "$COMPOSE" ;;
    "Nginx Proxy Manager") echo "  npm_data:" >> "$COMPOSE"; echo "  npm_letsencrypt:" >> "$COMPOSE" ;;
    "Tailscale") echo "  tailscale_state:" >> "$COMPOSE" ;;
  esac
done

cat >> "$COMPOSE" <<EOF

services:
EOF

echo "# Service blocks would be appended here by the full script" >> "$COMPOSE"
echo "# Run the web generator for a complete compose file:" >> "$COMPOSE"
echo "# https://wilcox101-maker.github.io/baremetal-lab/" >> "$COMPOSE"

cat > "$CONFIG_DIR/config-summary.txt" <<EOF
Baremetal Lab — Config Summary
Generated: $(date)

Hardware
  CPU cores:     $CPU
  RAM (GB):      $RAM
  Storage:       $STORAGE
  NICs:          $NICS
  Wi-Fi:         $WIFI
  USB devices:   ${USB_LIST[*]:-none}

Network
  LAN subnet:    $LAN_SUBNET
  Docker host:   $HOST_IP
  Timezone:      $TZ

Services
$(printf '  - %s\n' "${ENABLED[@]}")

Next steps
  1. Use the web generator for a full compose file
  2. Edit passwords
  3. docker compose up -d
EOF

echo
echo "Done."
echo "  Summary: $CONFIG_DIR/config-summary.txt"
echo "  Full compose: https://wilcox101-maker.github.io/baremetal-lab/"
